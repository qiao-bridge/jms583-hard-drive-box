#include "stc8g_delay.h"

/**
 * @brief 软件微秒级延时（粗略）
 * @param us 延时微秒数
 * @note 在11.0592MHz下，由于函数调用和循环开销，小于10us的延时误差较大
 *       适用于大于20us的场合
 */
void delay_us(unsigned int us)
{
    unsigned int i;
    // 11.0592MHz下，一个_nop_()大约是0.09us
    // 循环体本身有开销，这里按经验值调整
    // 计算依据：(us * 11059200) / 1000000 / 循环消耗指令数
    // 循环大约消耗6个指令周期，所以： us * 11059200 / 1e6 / 6 ≈ us * 1.84
    // 为了抵消函数调用和判断的开销，这里取 us * 1.5 左右的系数
    i = (us * 3) >> 1; // 等效于 us * 1.5
    while (--i)
        _nop_();
}

/**
 * @brief 软件毫秒级延时（较精确）
 * @param ms 延时毫秒数
 * @note 在11.0592MHz下，Keil C51优化等级为Default时的实测值
 *       适合按键消抖（10~20ms）等场合
 */
void delay_ms(unsigned int ms)
{
    unsigned int i, j;
    while (ms--)
    {
        // 内层循环1140次，实测约为1ms
        // 计算：11059200 / 12 / 1000 * 1ms ≈ 921个指令周期
        // 内层循环体大约消耗0.8个指令周期，所以 921 / 0.8 ≈ 1151
        // 考虑到外层循环开销，取1140是一个经过实测校准的经验值
        for (i = 1140; i > 0; i--)
            for (j = 1; j > 0; j--);
    }
}